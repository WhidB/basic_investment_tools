class Translator:
    def __init__(self, language, catalog):
        self.language = language
        self.messages = dict(EN)
        self.messages.update({catalog[k][1]: v for k,v in EXPLANATIONS.items()})
        self.fragments = sorted(((k,v) for k,v in self.messages.items() if len(k)>3), key=lambda pair:len(pair[0]), reverse=True)

    def __call__(self, text):
        if self.language != 'en' or not isinstance(text,str): return text
        if text in self.messages: return self.messages[text]
        for source,target in self.fragments:
            text = text.replace(source,target)
        return text

    def dataframe(self, frame):
        """Translate a display/export copy, without modifying stored results."""
        frame = frame.copy()
        frame.columns = [(c[:-3]+' '+self('순위')) if self.language=='en' and isinstance(c,str) and c.endswith(' 순위') else self(c) for c in frame.columns]
        for col in frame.select_dtypes(include=['object','str']).columns:
            if col in (self('해석'),self('단위'),self('reason')):
                frame[col] = frame[col].map(lambda v:self(v) if isinstance(v,str) else v)
        return frame
